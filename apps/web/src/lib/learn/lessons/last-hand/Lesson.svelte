<Part title="Count the gap">
  <p>
    In the last hand (East 4 in a standard game) only placement is left to play for, and <Term id="uma">uma</Term> makes
    each place worth 10,000 points. Know the gap to the player above you: a ron from them closes it by twice your hand,
    a ron from anyone else by your hand once.
  </p>
