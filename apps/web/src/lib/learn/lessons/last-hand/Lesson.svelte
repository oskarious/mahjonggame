  <Callout kind="ema"><p>In an East + South game the last hand is South 4.</p></Callout>
</Part>

<Part title="Tsumo hits the dealer hardest">
  <p>
    On a tsumo everyone pays, and the dealer pays a double share. Against the dealer a tsumo swings more than a ron
    from someone else.
  </p>
  <Exercise id="tsumo" />
</Part>

<Part title="Leading: play safe">
  <p>
    With the lead, a win you don't need is worth little and a deal-in can cost first place. Fold earlier than you
    would mid-game, above all against the player right behind you.
  </p>
