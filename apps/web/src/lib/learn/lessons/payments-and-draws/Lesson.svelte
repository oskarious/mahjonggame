<Part title="Who pays for a win">
  <p>
    Ron: the discarder pays everything. A non-dealer's self-draw: the dealer pays twice what each other player pays
    (written "700 / 1300").
  </p>
  <Exercise id="tsumo" />
</Part>

<Part title="Counters and riichi sticks">
  <p>
    Each <Term id="honba">counter</Term> (after a dealer win or a draw) adds 300 to the next win. Every
    <Term id="riichi-stick">riichi stick</Term> on the table goes to the next winner.
  </p>
  <Exercise id="gain" />
</Part>

<Part title="When the wall runs out">
  <p>
    With no winner, players in tenpai show their hands and the others (<Term id="noten">noten</Term>) pay them 3000 in
    total.
  </p>
  <Exercise id="alone" />
</Part>

<Part title="Splitting the 3000">
  <p>The 3000 is shared: 1 player in tenpai gets 1000 from each; 3 in tenpai each get 1000 from the one who isn't.</p>
  <Exercise id="two" />
</Part>

<Part title="Who deals next">
  <p>
    The dealer stays (and a counter is added) after winning, or when in tenpai at a draw. Otherwise the deal passes to
    the right.
  </p>
  <Exercise id="dealer" />
