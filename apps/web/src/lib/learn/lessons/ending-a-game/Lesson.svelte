<Part title="Rounds">
  <p>
    In a round every player deals at least once: East 1, East 2 and so on. Riichi Arena's standard game is East-only,
    about 15-20 minutes; East + South (a <Term id="hanchan">hanchan</Term>) is the tournament length.
  </p>
  <Exercise id="deals" />
</Part>

<Part title="The end of the game">
  <p>
    The game ends after the last deal of the last round. On Riichi Arena it also ends at once if a player drops below
    zero.
  </p>
  <Exercise id="bust" />
</Part>

<Part title="Placement and uma">
  <p>
    At the end a placement bonus, <Term id="uma">uma</Term>, is added: +15,000, +5,000, -5,000, -15,000. Your rating
    moves by placement, so near the end a cheap win that moves you up a place often beats chasing a big hand.
  </p>
  <Exercise id="uma" />
  <Callout kind="ema"><p>EMA tournaments play East + South, without going bust.</p></Callout>
</Part>
