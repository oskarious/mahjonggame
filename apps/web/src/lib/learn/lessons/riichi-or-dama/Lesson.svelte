<Part title="Three reasons to riichi">
  <p>
    Declare <Term id="riichi">riichi</Term> when at least one of these is true: the hand has another han (dora count),
    the wait is good, or you are the dealer. A cheap, non-dealer hand with no other han and a bad wait is the one to
    think twice about.
  </p>
  <Exercise id="reasons" />
</Part>

<Part title="Riichi right away">
  <p>
    Waiting for a better shape rarely pays: one specific tile comes about once in 30 draws. If you are going to
    riichi, do it as soon as you are in tenpai.
  </p>
  <Exercise id="now" />
</Part>

<Part title="Value or wait">
  <p>
    With two ways to tenpai, the wider wait is usually right. But while the hand is cheap (under about 5200), one more
    han doubles it: then keep the han, a dora or a yaku, even on a worse wait.
  </p>
  <Exercise id="value" />
</Part>

<Part title="When to stay dama">
  <p>
    Stay quiet (<Term id="dama">dama</Term>) when the hand is already big, about 7700 or more, late in the hand; with a
    very bad wait that has 1 or 2 tiles left; or when a win without riichi already secures first place in the last hand.
    And a hand without a yaku of its own can only win dama by self-draw: riichi it, or don't aim for tenpai.
  </p>
  <Exercise id="dama" />
</Part>
